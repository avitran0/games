#[cfg(test)]
mod tests {
    use super::Color;

    #[test]
    fn palette_file_matches_color_indices() {
        let mut rows = include_str!("../../assets/palette.pal").lines();
        assert_eq!(rows.next(), Some("JASC-PAL"));
        assert_eq!(rows.next(), Some("0100"));
        assert_eq!(
            rows.next().unwrap().parse::<usize>().unwrap(),
            Color::COUNT + 1
        );
        assert_eq!(rows.next(), Some("0 0 0 0"));
        for color in Color::ALL {
            let row = rows.next().expect("palette file color");
            let rgba: Vec<u8> = row
                .split_ascii_whitespace()
                .map(|value| value.parse().expect("palette channel"))
                .collect();
            let [red, green, blue] = color.rgb();
            assert_eq!(rgba, [red, green, blue, 255]);
        }
        assert!(rows.next().is_none());
    }
}
