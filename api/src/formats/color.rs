#[cfg(test)]
mod tests {
    use super::Color;

    #[test]
    fn palette_starts_with_grays_and_omits_requested_purple() {
        assert_eq!(Color::ALL.len(), 255);
        assert!(Color::ALL[..16].iter().all(|color| {
            let [red, green, blue] = color.rgb();
            red == green && green == blue
        }));
        assert!(
            !Color::ALL
                .iter()
                .any(|color| color.rgb() == [0x7f, 0x00, 0xff])
        );
    }

    #[test]
    fn green_band_groups_muted_and_vivid_shades() {
        let names: Vec<_> = Color::ALL.iter().map(|color| color.name()).collect();
        let position = |name| {
            names
                .iter()
                .position(|color_name| *color_name == name)
                .unwrap()
        };
        assert_eq!(position("DeYork2"), position("BayLeaf") + 1);
        assert_eq!(position("Green3"), position("Green2") + 1);
        assert!(position("Green2") > position("DeYork2"));
    }

    #[test]
    fn palette_file_matches_color_indices() {
        let rows = include_str!("../../../assets/palette.pal").lines().skip(4);
        let mut rows = rows;
        for color in Color::ALL {
            let row = rows.next().expect("palette file color");
            let rgb: Vec<u8> = row
                .split_ascii_whitespace()
                .take(3)
                .map(|value| value.parse().expect("palette RGB value"))
                .collect();
            assert_eq!(rgb, color.rgb());
        }
        assert!(rows.next().is_none());
    }
}
