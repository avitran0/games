macro_rules! define_palette {
    ($( $color:ident => [$red:literal, $green:literal, $blue:literal] ),* $(,)?) => {
        #[repr(u8)]
        #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
        pub enum Color { Transparent = 0, $( $color, )* }
        impl Color {
            pub const COUNT: usize = 255;
            pub const ALL: [Self; Self::COUNT] = [$(Self::$color),*];
            pub const fn index(self) -> u8 { self as u8 }
            pub const fn name(self) -> &'static str {
                match self { Self::Transparent => "Transparent", $(Self::$color => stringify!($color)),* }
            }
            pub const fn rgb(self) -> [u8; 3] {
                match self { Self::Transparent => [0, 0, 0], $(Self::$color => [$red, $green, $blue]),* }
            }
        }
    };
}

